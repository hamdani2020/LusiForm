"""Build iam-reference.json for a template version from the AWS Service Authorization Reference.

The Service Authorization Reference is AWS's machine-readable list of IAM actions, the resource
types each action accepts, and the condition keys that apply. This script keeps only what the
template's IAM catalog uses, so the sandbox policy can be generated and verified offline.

Usage (run in the worker container; standard library only):

    python scripts/build_iam_reference.py <service-json-dir> <version-dir> --retrieved YYYY-MM-DD

<dir-with-service-json> holds one file per IAM service prefix, downloaded from
https://servicereference.us-east-1.amazonaws.com/v1/<prefix>/<prefix>.json
(ec2.json, iam.json, elasticloadbalancing.json, ...). The retrieval date is an argument so
the output never depends on the clock.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

SOURCE = "https://servicereference.us-east-1.amazonaws.com/ (AWS Service Authorization Reference)"


def _labels(catalog: dict[str, Any]) -> list[str]:
    return sorted(catalog["arns"])


def _actions(catalog: dict[str, Any]) -> list[str]:
    actions: set[str] = set()
    for entry in catalog["types"].values():
        for role in ("create", "write", "read", "tag"):
            actions.update(entry.get(role, []))
    for extra in catalog["extras"]:
        actions.update(extra["actions"])
    return sorted(actions)


def build(catalog: dict[str, Any], reference_dir: Path, retrieved: str) -> dict[str, Any]:
    services: dict[str, dict[str, Any]] = {}

    def service(prefix: str) -> dict[str, Any]:
        if prefix not in services:
            path = reference_dir / f"{prefix}.json"
            if not path.is_file():
                raise SystemExit(f"missing reference file for service {prefix!r}: {path}")
            services[prefix] = json.loads(path.read_text())
        return services[prefix]

    labels = _labels(catalog)
    label_set = set(labels)

    arn_formats: dict[str, list[str]] = {}
    resource_keys: dict[str, list[str]] = {}
    for label in labels:
        prefix, name = label.split(":", 1)
        resource = next((r for r in service(prefix)["Resources"] if r["Name"] == name), None)
        if resource is None:
            raise SystemExit(f"resource type {label!r} not found in the {prefix} reference")
        arn_formats[label] = list(resource["ARNFormats"])
        resource_keys[label] = sorted(resource.get("ConditionKeys", []))

    actions_out: dict[str, Any] = {}
    for full in _actions(catalog):
        prefix, name = full.split(":", 1)
        found = next((a for a in service(prefix)["Actions"] if a["Name"] == name), None)
        if found is None:
            raise SystemExit(f"action {full!r} not found in the {prefix} reference")
        resources: dict[str, list[str]] = {}
        for res in found.get("Resources") or []:
            label = f"{prefix}:{res['Name']}"
            if label in label_set:
                keys = set(res.get("ConditionKeys", [])) | set(resource_keys[label])
                resources[label] = sorted(keys)
        actions_out[full] = {
            "keys": sorted(found.get("ActionConditionKeys", [])),
            "resource_types": len(found.get("Resources") or []),
            "resources": dict(sorted(resources.items())),
        }

    versions = {p: str(services[p].get("Version", "")) for p in sorted(services)}
    return {
        "schema": "lusiform.iam-reference/1",
        "source": SOURCE,
        "retrieved": retrieved,
        "service_versions": versions,
        "notes": [
            "Generated by scripts/build_iam_reference.py from the catalog's actions and types.",
            "Do not edit by hand.",
            "keys: condition keys that apply to the action as a whole.",
            "resource_types: how many resource types the action accepts in total (0 means '*').",
            "resources: for each catalog resource type the action accepts, the condition keys that",
            "apply: the action's own keys for that resource type plus the resource type's keys.",
        ],
        "arn_formats": arn_formats,
        "actions": actions_out,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("reference_dir", type=Path)
    parser.add_argument("version_dir", type=Path)
    parser.add_argument(
        "--retrieved", required=True, help="date the reference was downloaded, YYYY-MM-DD"
    )
    args = parser.parse_args(argv)

    catalog = json.loads((args.version_dir / "iam-catalog.json").read_text())
    reference = build(catalog, args.reference_dir, args.retrieved)
    out = args.version_dir / "iam-reference.json"
    out.write_text(json.dumps(reference, indent=2) + "\n")
    actions, types = len(reference["actions"]), len(reference["arn_formats"])
    print(f"wrote {out} ({actions} actions, {types} resource types)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
